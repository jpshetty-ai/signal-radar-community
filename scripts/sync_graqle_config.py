"""Generate graqle.yaml from config/models.yaml so the two cannot drift.

    python scripts/sync_graqle_config.py           # write graqle.yaml
    python scripts/sync_graqle_config.py --check   # exit 1 if graqle.yaml is stale (use in CI / pre-commit)

Mapping (Graqle 0.85):
  reasoning role   -> model.backend / model.model  (what `graq reason` and `graq mcp serve` use)
  each chat role   -> models.<role> named profile  (selectable inside Graqle by name)
  embedding role   -> NOT mappable: Graqle embeddings support only local|bedrock|simple.
                      Graqle keeps its own sentence-transformers model for graph retrieval;
                      the project's embedding role is used by our own code. Reported as a warning.

Graqle's CLI falls back to a mock backend (with only a console warning) when a backend is
misconfigured, so this script also refuses providers Graqle's CLI cannot build.

The graph section comes from config/graph.yaml (ADR-0017). With connector: neo4j, graq reads the Neo4j copy
and keeps `path` as its fallback; the password is only ever an ${ENV} reference. graq 0.85 reads
graph.connector at runtime (its newer `backends:` section is ignored until a later release), so this is the
switch even though graq prints a deprecation warning for it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from signal_radar.config import load_graph, load_models  # noqa: E402

GRAQLE_CHAT_BACKENDS = {"anthropic", "openai", "ollama"}  # what graqle.cli.main._create_backend_from_config builds
HEADER = (
    "# GENERATED by scripts/sync_graqle_config.py from config/models.yaml. Do not edit by hand.\n"
    "# Dedicated to Signal Radar: the graph lives under data/graqle/, never shared with other projects.\n"
)


def graph_section(graph_path: Path | None = None) -> dict:
    g = load_graph(graph_path)
    if g.connector == "networkx":
        return {"connector": "networkx", "path": g.file}
    n = g.neo4j
    return {"connector": "neo4j", "path": g.file, "uri": n.uri, "username": n.username,
            "password": "${" + n.password_env + "}", "database": n.database}


def build(models_path: Path | None = None, graph_path: Path | None = None) -> tuple[dict, list[str]]:
    cfg = load_models(models_path)
    warnings: list[str] = []

    # Roles may list ranked candidates (ADR-0013); Graqle gets each role's first choice, mapped by provider kind.
    reasoning = cfg.primary("reasoning")
    kind = cfg.kind_of(reasoning.provider)
    if kind not in GRAQLE_CHAT_BACKENDS:
        raise SystemExit(f"reasoning provider {reasoning.provider!r} (kind {kind!r}) is not supported by Graqle's CLI")

    model: dict = {"backend": kind, "model": reasoning.model}
    prov = cfg.providers.get(reasoning.provider)
    if kind == "ollama":
        model["host"] = (prov.default_host if prov else None) or "http://localhost:11434"
    elif prov and prov.api_key_env:
        model["api_key"] = "${" + prov.api_key_env + "}"  # Graqle resolves ${VAR} at runtime
    if kind == "openai" and prov and prov.base_url:
        model["endpoint"] = prov.base_url

    named = {}
    for role in ("extraction", "reasoning", "writing"):
        spec = cfg.primary(role)
        rkind = cfg.kind_of(spec.provider)
        if rkind in GRAQLE_CHAT_BACKENDS:
            named[role] = {"backend": rkind, "model": spec.model}
        else:
            warnings.append(f"role {role}: provider {spec.provider} has no Graqle backend; profile skipped")

    emb = cfg.primary("embedding")
    warnings.append(
        f"embedding role is {emb.key}; Graqle cannot use it and keeps local sentence-transformers "
        "for graph retrieval. Vectors from the two are not comparable."
    )

    doc = {
        "project_name": "signal-radar",
        "domain": "custom",
        "model": model,
        "models": named,
        "graph": graph_section(graph_path),
        "embeddings": {"backend": "local", "model": "sentence-transformers/all-MiniLM-L6-v2"},
        "cost": {"prefer_local": True, "fallback_to_api": False},
        "logging": {"trace_dir": "data/graqle/traces"},
    }
    return doc, warnings


def render(doc: dict) -> str:
    return HEADER + yaml.safe_dump(doc, sort_keys=False)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if graqle.yaml differs from what would be generated")
    ap.add_argument("--out", type=Path, default=ROOT / "graqle.yaml")
    args = ap.parse_args()

    doc, warnings = build()
    text = render(doc)
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)

    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"{args.out.name} is out of date; run scripts/sync_graqle_config.py", file=sys.stderr)
            return 1
        print(f"{args.out.name} is in sync")
        return 0

    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
